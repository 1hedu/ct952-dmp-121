static void flush(void){
    REG_CACHE &= ~0x00040000u; REG_CACHE |= 0x00400000u;
    for (volatile int i = 0; i < 256; i++) __asm__ __volatile__("nop");
    REG_CACHE |= 0x00040000u;
}

static void px(int x, int y, uint8_t c){
    uint32_t off;
    if (x < 0 || y < 0 || x >= VIS_W || (uint32_t)y >= ROWS) return;
    off = (uint32_t)y * PITCH + ((uint32_t)x >> 1);
    if (off >= REGION) return;
    if (x & 1) FB[off] = (uint8_t)((FB[off] & 0xF0) | (c & 0x0F));
    else       FB[off] = (uint8_t)((FB[off] & 0x0F) | ((c & 0x0F) << 4));
}

static void glyph(int x0, int y0, uint8_t ch, uint8_t fg, int s){
    const uint8_t *g;
    if (ch < 0x20 || ch > 0x7F) ch = 0x20;
    g = font8x8[ch - 0x20];
    for (int r = 0; r < 8; r++)
        for (int c = 0; c < 8; c++)
            if (g[r] & (1u << c))
                for (int sy = 0; sy < s; sy++)
                    for (int sx = 0; sx < s; sx++)
                        px(x0 + c*s + sx, y0 + r*s + sy, fg);
}

static void text(int x0, int y0, const char *str, uint8_t fg, int s){
    for (int i = 0; str[i]; i++) glyph(x0 + i*8*s, y0, (uint8_t)str[i], fg, s);
}

int pyapp_main(void){
    REG_SYSCFG1 &= ~0x10000000u;               /* keep the watchdog dead */

    for (uint32_t i = 0; i < REGION; i++) FB[i] = 0;   /* transparent */

    /* 82 lines available. Title at 3x (24px), body at 2x (16px). */
    text(8,  2,  "CT952A LIVE", C_HI,  3);
    text(8,  30, "PITCH 292 CONFIRMED", C_TXT, 2);
    text(8,  48, "BARE METAL ON SILICON", C_TXT, 2);
    text(8,  64, "NEXT: MICROPYTHON", C_HI,  2);

    flush();
    for (;;){}
    return 0;
}
