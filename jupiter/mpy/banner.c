/* CT952A on-screen banner -- milestone 1: legible text on the real panel.
 *
 * The row pitch is the thing that defeated every earlier attempt. It is now
 * MEASURED and CONFIRMED on hardware: **292 bytes per display line** (= 584 px at
 * 4bpp). Confirmed by a self-identifying probe that drew "288"/"292"/"296" each
 * using its own value as the pitch -- only 292 came out legible on the frame.
 *
 * Note the pitch is NOT any register value found so far: not the GDI region width
 * (308 B / 616 px), not the OSD window width (360 B / 720 px). REG_MCU_VCR23>>16
 * reads 308 while the panel scans 292, an unexplained discrepancy (see 10.19), so
 * 292 is hardcoded from measurement rather than read from a register.
 *
 * Environment inherited from the AP loader (aploader.c STEP2), all of it left
 * alone -- writing display registers clobbers the loader's working config:
 *   - 4bpp OSD plane at DS_OSDFRAME_ST_AP = 0x40084000 (dvd_dram_16m.h, 2MB part)
 *   - the loader's live palette: index 0 = transparent colour key, 1 = yellow,
 *     2 = white. We draw on transparent so the panel's own background shows
 *     through, which gives maximum contrast and avoids full-region banding.
 *   - the region is painted ~twice inside the taller 240-line OSD window; that
 *     duplication is cosmetic and left as-is.
 * All writes are clamped to the 24576-byte region (DS_OSDFRAME_ST_AP..END_AP).
 */
